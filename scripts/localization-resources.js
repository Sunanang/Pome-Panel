'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { parseTree } = require('jsonc-parser');
const root = path.join(__dirname, '..');
const languages = require('../localization/languages.json');
function readDictionary(file) {
  const text = fs.readFileSync(file, 'utf8'), errors = [];
  const tree = parseTree(text, errors, { disallowComments: true, allowTrailingComma: false });
  if (errors.length || tree?.type !== 'object') throw new Error(`Invalid language JSON: ${file}`);
  function check(node) {
    if (node.type === 'object') {
      const seen = new Set();
      for (const property of node.children || []) {
        const name = property.children[0].value;
        if (seen.has(name)) throw new Error(`Duplicate translation key: ${name}`);
        seen.add(name); check(property.children[1]);
      }
    }
  }
  check(tree);
  return JSON.parse(text);
}
const parameters = text => [...String(text).matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map(match => match[1]).sort();
function validate(resources) {
  const keys = Object.keys(resources['en-US']).sort();
  for (const locale of Object.keys(resources)) if (JSON.stringify(keys) !== JSON.stringify(Object.keys(resources[locale]).sort())) throw new Error(`Language keys differ: ${locale}`);
  for (const key of keys) {
    const original = resources['zh-CN'][key];
    const expected = parameters(typeof original === 'string' ? original : original.other);
    for (const locale of Object.keys(resources)) {
      const value = resources[locale][key];
      if (typeof value !== 'string' && (!value || Array.isArray(value) || typeof value !== 'object' || typeof value.other !== 'string')) throw new Error(`Invalid translation: ${locale}/${key}`);
      for (const text of typeof value === 'string' ? [value] : Object.values(value || {})) {
        if (typeof text !== 'string' || !text.trim() || /<\/?[A-Za-z][^>]*>/.test(text)) throw new Error(`Invalid translation: ${locale}/${key}`);
        if (JSON.stringify(parameters(text)) !== JSON.stringify(expected)) throw new Error(`Parameters differ: ${locale}/${key}`);
      }
    }
  }
  return keys.length;
}
function generatedResources() {
  const resources = Object.fromEntries(languages.map(({ id }) => [id, readDictionary(path.join(root, 'localization/locales', `${id}.json`))]));
  validate(resources);
  const outputs = new Map();
  const script = `// Generated by scripts/localization-resources.js. Edit localization/locales/*.json.\nglobalThis.PomeLanguages = ${JSON.stringify(languages)};\nglobalThis.PomeTranslations = ${JSON.stringify(resources)};\n`;
  outputs.set('localization/resources.js', script);
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'localization/catalog.json'), 'utf8'));
  const websiteKeys = new Set(catalog.filter(row => row.locations.some(location => location.file.startsWith('website/'))).map(row => row.key));
  websiteKeys.add('settings.language');
  const websiteResources = Object.fromEntries(languages.map(({ id: locale }) => [locale,
    Object.fromEntries(Object.entries(resources[locale]).filter(([key]) => websiteKeys.has(key) || key.startsWith('website.')))]));
  outputs.set('website/app/translations.json', JSON.stringify(websiteResources, null, 2) + '\n');
  outputs.set('website/app/languages.json', JSON.stringify(languages, null, 2) + '\n');
  outputs.set('fnos/app/ui/i18n/resources.js', script);
  outputs.set('fnos/app/ui/i18n/runtime.js', fs.readFileSync(path.join(root, 'localization/runtime.js'), 'utf8'));
  outputs.set('fnos/app/ui/i18n/browser.js', fs.readFileSync(path.join(root, 'renderer/localization.js'), 'utf8'));
  const wizardFiles = ['install', 'config', 'upgrade', 'uninstall'];
  const references = new Set(wizardFiles.flatMap(file => [...fs.readFileSync(path.join(root, 'fnos/wizard', file), 'utf8').matchAll(/\$\{wizard\.([^}]+)\}/g)].map(match => match[1])));
  for (const locale of ['en-US', 'zh-CN']) {
    const messages = resources[locale];
    const lines = ['[nas]', ...['packageDescription', 'packageChangelog'].map(key => `${key}=${JSON.stringify(messages[`nas.${key}`])}`), '', '[wizard]'];
    for (const ref of [...references].sort()) {
      const key = Object.keys(messages).find(candidate => candidate.startsWith('copy.') && candidate.slice(5).replaceAll('.', '_') === ref);
      if (!key || typeof messages[key] !== 'string') throw new Error(`Missing wizard resource: ${locale}/${ref}`);
      lines.push(`${ref}=${JSON.stringify(messages[key])}`);
    }
    outputs.set(`fnos/i18n/${locale}`, lines.join('\n') + '\n');
  }
  const escapeNsis = text => text.replaceAll('$', '$$').replaceAll('"', '$\\"').replaceAll('\r', '').replaceAll('\n', '$\\r$\\n');
  const nsis = ['; Generated from localization/locales/*.json.'];
  for (const [name, key] of [['POME_WELCOME_TITLE', 'installer.welcomeTitle'], ['POME_WELCOME_TEXT', 'installer.welcomeText'], ['POME_DIRECTORY_TEXT', 'installer.directoryText']]) {
    for (const [locale, id] of [['en-US', 1033], ['zh-CN', 2052]]) nsis.push(`LangString ${name} ${id} "${escapeNsis(resources[locale][key])}"`);
  }
  outputs.set('build/i18n/messages.nsh', nsis.join('\n') + '\n');
  for (const { id: locale, mac: directory } of languages) {
    const lines = Object.keys(resources[locale]).filter(key => key.startsWith('mac.')).sort()
      .map(key => `${JSON.stringify(key.slice(4))} = ${JSON.stringify(resources[locale][key])};`);
    outputs.set(`build/i18n/${directory}.lproj/InfoPlist.strings`, lines.join('\n') + '\n');
  }
  return outputs;
}
function generate(check = false) {
  for (const [file, content] of generatedResources()) {
    const target = path.join(root, file);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error(`Generated localization resource is stale: ${file}`);
    } else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
  }
}
if (require.main === module) {
  try { generate(process.argv.includes('--check')); console.log('Localization resources verified'); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { readDictionary, validate, generatedResources, generate };
